/**
 * 締め日・支給日の数値を「○日」または「末日」に整形
 */
export const formatClosingDay = (day?: number | string | null): string => {
  if (day === null || day === undefined || day === WORDS_COMMON.EMPTY_VALUE) return WORDS_COMMON.DASH;
  const num = Number(day);
  if (isNaN(num)) return WORDS_COMMON.DASH;
  if (num === WORDS_TIME.CLOSING_DAY_LAST_NUM || String(day) === WORDS_TIME.CLOSING_DAY_LAST_VALUE) {
    return WORDS_TIME.CLOSING_DAY_LAST;
  }
  return `${num}${WORDS_TIME.DAY_SUFFIX}`;
};

/**
 * 支給月区分の文字列を「当月」「翌月」「翌々月」に整形
 */
export const formatClosingMonthType = (type?: string | null): string => {
  if (!type) return WORDS_COMMON.DASH;
  const opt = CLOSING_MONTH_TYPE_OPTIONS.find(o => o.value === type);
  return opt ? opt.label : type;
};
